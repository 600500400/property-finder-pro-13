CREATE TABLE public.csu_house_prices_okres (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kraj text NOT NULL,
  okres text,
  level text NOT NULL CHECK (level IN ('okres','kraj_total','cr_total')),
  avg_size_m2 numeric,
  price_2023_2025 integer,
  transfers integer,
  price_2023 integer,
  price_2024 integer,
  price_2025 integer,
  band text,
  band_price_raw integer,
  band_price_uplifted integer,
  uplift_factor numeric,
  UNIQUE (kraj, okres, level, band)
);
GRANT SELECT ON public.csu_house_prices_okres TO anon, authenticated;
GRANT ALL ON public.csu_house_prices_okres TO service_role;
ALTER TABLE public.csu_house_prices_okres ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Public ČSÚ okres reference read" ON public.csu_house_prices_okres FOR SELECT TO anon, authenticated USING (true);
CREATE INDEX csu_house_prices_okres_lookup_idx ON public.csu_house_prices_okres (kraj, okres, band);

